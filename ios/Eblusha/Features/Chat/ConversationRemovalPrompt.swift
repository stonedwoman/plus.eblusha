import Foundation

/// Тексты подтверждения «убрать беседу» в ОДНОМ месте.
///
/// Раньше их было два: список чатов спрашивал с пояснением последствий
/// (ChatListView.deleteAlert), а шапка открытого чата — голым вопросом из двух слов, хотя
/// действие то же и необратимое. Разнобой внутри одной платформы и появился именно потому,
/// что строки лежали в двух вьюхах; теперь у обеих один источник.
enum ConversationRemovalPrompt {

    /// [isSecret] — секретный V2-тред, [isGroup] — групповая беседа (иначе диалог 1:1),
    /// [isBotChat] — «Чат с Еблушей»: он не удаляется, а выключается (история сохраняется).
    static func texts(
        isSecret: Bool, isGroup: Bool, isBotChat: Bool = false
    ) -> (title: String, message: String, action: String) {
        if isBotChat && !isSecret {
            return (
                "Выключить чат с Еблушей?",
                "Чат пропадёт из списка, переписка сохранится. Включить снова — в профиле, «Чат с Еблушей».",
                "Выключить"
            )
        }
        if isSecret {
            return (
                "Закрыть секретный чат?",
                "Секретный чат будет закрыт и скрыт у всех участников.",
                "Закрыть"
            )
        }
        if isGroup {
            return (
                "Выйти из беседы?",
                "Беседа исчезнет из вашего списка, остальные участники останутся.",
                "Выйти"
            )
        }
        return (
            "Удалить чат?",
            "Переписка будет удалена у всех участников безвозвратно.",
            "Удалить"
        )
    }
}
