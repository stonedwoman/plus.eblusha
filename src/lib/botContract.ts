/**
 * Контракт «сервер ↔ сервис бота Еблуша» (очередь BullMQ `bot`). Сервис бота держит копию этих
 * типов (bot/src/api/types.ts, BotJob).
 *
 * Версии. `v` — несовместимая смена формы: бот отвергает задачу с чужим `v` (старый бот принимает только
 * v: 1), поэтому `v` НЕ поднимаем, пока можно обойтись добавочными полями. Добавочные поля — ревизия `rev`
 * (нет поля — ревизия 1): старый бот их просто не читает, новый бот без них работает как раньше. Так
 * старый бот с новым сервером и новый бот со старым сервером не ломаются.
 *   rev 1 — триггер + цепочка ответов (chain).
 *   rev 2 — плюс `history`: контекст без цитирования (решение владельца 2026-10-10, см. BotJobHistory).
 *
 * Сервер кладёт задачу ТОЛЬКО на сообщение, адресованное боту (src/lib/systemBot.ts →
 * detectBotAddress), в обычной (не секретной) беседе. Остальную переписку людей бот не видит:
 * он не участник, а в задачу идут триггер, цепочка его ответов (replyTo вверх) и history — в «Чате с
 * Еблушей» недавняя история этого чата, в обычной беседе только разговоры с ботом (обращения + его ответы).
 */

/** Как сообщение оказалось адресовано боту. */
export type BotAddressVia =
  /** «Еблуша,» / «Еблуша:» / «Еблуша!» в начале (регистр, е/ё и похожая латиница не важны). */
  | "name"
  /** /eb или /еб в начале. */
  | "command"
  /** Ответ (replyToId) на сообщение бота. */
  | "reply"
  /** Личный чат пользователя с ботом — там всё адресовано боту. */
  | "botchat"
  /** Клиент явно включил режим «Спросить» (metadata.botAsk === true). */
  | "explicit";

/**
 * Вид беседы глазами бота:
 *  - "bot"   — личный чат пользователя с ботом (настройка «Чат с Еблушей»): ответ видит только он;
 *  - "dm"    — личка двух людей: ответ увидят ОБА;
 *  - "group" — группа: ответ увидят все участники.
 */
export type BotConversationKind = "bot" | "dm" | "group";

export interface BotJobAttachment {
  /** /api/files/<ключ> — отдаётся без авторизации, `?thumb=1` — серверное превью картинки. */
  url: string;
  type: "IMAGE" | "VIDEO" | "AUDIO" | "FILE";
  size: number | null;
  metadata: Record<string, unknown> | null;
}

export interface BotJobMessage {
  id: string;
  senderId: string;
  /** displayName отправителя (может быть null). */
  senderName: string | null;
  /** Сообщение самого бота (Message.isBot). */
  isBot: boolean;
  type: "TEXT" | "IMAGE" | "VIDEO" | "AUDIO" | "FILE";
  content: string | null;
  /** ISO. */
  createdAt: string;
  replyToId: string | null;
  attachments: BotJobAttachment[];
}

/**
 * Контекст без цитирования (rev 2). Только эта беседа; без удалённых, истёкших, системных записей и
 * звонков, без самого триггера и без сообщений новее него; от старшего к младшему; текст каждого
 * сообщения не длиннее BOT_JOB_HISTORY_TEXT_MAX (дальше «…»). Сообщения цепочки (chain) тоже могут
 * сюда попасть — бот убирает дубли сам.
 */
export interface BotJobHistory {
  /**
   * "botchat" — «Чат с Еблушей» (kind "bot"): последние сообщения этого чата, обе стороны
   *             (до BOT_JOB_HISTORY_BOTCHAT_MAX, без приветствия бота). Бот берёт из них ~40 в пределах
   *             своего бюджета токенов.
   * "recent"  — обычная беседа (kind "dm" | "group"): ТОЛЬКО разговоры с ботом за BOT_JOB_RECENT_WINDOW_MS
   *             до триггера — обращения к нему от любого участника (metadata.botAsk, ставит только сервер)
   *             и его ответы (isBot). Остальная переписка людей сюда не попадает. Ответ бота, чьё обращение
   *             удалено или истекло, тоже не попадает; обращение к ответу из окна — попадает, даже если
   *             оно старше окна.
   */
  mode: "botchat" | "recent";
  /** Окно "recent", мс; у "botchat" — null. */
  windowMs: number | null;
  messages: BotJobMessage[];
}

export interface BotJobV1 {
  v: 1;
  /** Ревизия добавочных полей (см. шапку). Нет поля — 1. */
  rev?: number;
  kind: "message";
  /** Когда поставлено (мс, часы сервера). Бот выбрасывает слишком старые задачи. */
  enqueuedAt: number;
  /**
   * Разрешение ответить в ЭТУ беседу: POST /api/bot/messages|typing|react с {grant}. Без него бот
   * писать в беседу не может (кроме уведомлений в личный чат с ботом — POST /api/bot/messages {userId}).
   */
  grant: string;
  /** До какого момента (мс) разрешение действует. */
  grantExpiresAt: number;
  via: BotAddressVia;
  conversation: {
    id: string;
    kind: BotConversationKind;
    /** Название группы (у лички и чата с ботом — null). */
    title: string | null;
    /** Люди-участники беседы (id, без бота) — для правила «данные игроков только игрокам». */
    participantIds: string[];
  };
  author: { id: string; displayName: string | null };
  /** Сообщение-триггер (как сохранено; текст — с «Еблуша,» / «/eb», бот срезает сам). */
  message: BotJobMessage;
  /**
   * Цепочка ответов: предки триггера по replyTo от СТАРШЕГО к родителю триггера (триггера в ней нет),
   * не длиннее BOT_JOB_CHAIN_MAX - 1. Только эта беседа, без удалённых и истёкших.
   */
  chain: BotJobMessage[];
  /** rev 2: контекст без цитирования. Нет — сервер старый или история не загрузилась (бот живёт цепочкой). */
  history?: BotJobHistory;
}

export type BotJob = BotJobV1;

/** Текущая ревизия задачи, которую кладёт этот сервер. */
export const BOT_JOB_REV = 2;

/** Сколько сообщений (с триггером) уходит боту цепочкой. */
export const BOT_JOB_CHAIN_MAX = 12;
/**
 * «Чат с Еблушей»: сколько последних сообщений отдать боту. Модель видит ~40 (BOT_HISTORY_MAX_MESSAGES
 * бота); запас — чтобы бот мог держать начало окна на месте несколько обменов подряд (кэш промпта).
 */
export const BOT_JOB_HISTORY_BOTCHAT_MAX = 60;
/** Обычная беседа: окно «недавних разговоров с ботом». */
export const BOT_JOB_RECENT_WINDOW_MS = 30 * 60 * 1000;
/** Обычная беседа: не больше стольких сообщений (обращения + ответы бота) за окно. */
export const BOT_JOB_RECENT_MAX = 40;
/** Текст одного сообщения истории в задаче (символов). Бот ужимает ещё сильнее под свой бюджет. */
export const BOT_JOB_HISTORY_TEXT_MAX = 4000;
