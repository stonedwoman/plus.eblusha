/**
 * Какую память обещать: "full" — всё (сводка + дословно); "recent" — сжатие выключено (BOT_MEMORY_MODEL=off),
 * давнее забывается; "off" — памяти нет (BOT_MEMORY_TAIL_TOKENS=0). true/false — старые вызовы (full/off).
 */
export type MemoryPromise = "full" | "recent" | "off";

/** Системный текст: обещает ровно ту память, что есть. Постоянный на процесс (кэш). */
export function buildSystemPrompt(modulePrompts: string[], opts: { memory?: boolean | MemoryPromise } = {}): string {
  const mode: MemoryPromise = opts.memory === false ? "off" : opts.memory === true || opts.memory === undefined ? "full" : opts.memory;
  const intro = mode === "off" ? INTRO_NO_MEMORY : mode === "recent" ? INTRO_MEMORY_RECENT : INTRO_MEMORY;
  const base = `${intro}\n\n${BODY}`;
  if (modulePrompts.length === 0) return base;
  return `${base}\n\n${modulePrompts.join("\n\n")}`;
}

