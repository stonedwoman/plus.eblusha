export function buildSystemPrompt(modulePrompts: string[]): string {
  if (modulePrompts.length === 0) return BASE_SYSTEM_PROMPT;
  return `${BASE_SYSTEM_PROMPT}\n\n${modulePrompts.join("\n\n")}`;
}

